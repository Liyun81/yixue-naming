def main():
    # 校验：64 条、卦名唯一、上下卦合法
    assert len(GUA) == 64, f"卦数应为 64，实际 {len(GUA)}"
    names = [g[0] for g in GUA]
    assert len(set(names)) == 64, "卦名重复"
    combos = set()
    for name, up, low, gong, *_ in GUA:
        assert up in BAGUA and low in BAGUA, f"{name} 卦象非法"
        assert gong in GONG_WUXING, f"{name} 宫位非法"
        key = (up, low)
        assert key not in combos, f"{name} 上下卦组合重复 {key}"
        combos.add(key)
    assert len(combos) == 64, "上下卦组合未覆盖全 64"

    # 八宫校验：每宫 8 卦
    from collections import Counter
    c = Counter(g[3] for g in GUA)
    assert all(v == 8 for v in c.values()), f"八宫分布异常 {dict(c)}"

    gua_map = {}
    for idx, (name, up, low, gong, xiang, brief, tendency, advice) in enumerate(GUA, 1):
        gua_map[name] = {
            "no": idx,
            "name": name,
            "upper": up,
            "lower": low,
            "upper_no": BAGUA[up]["no"],
            "lower_no": BAGUA[low]["no"],
            "symbol": BAGUA[up]["symbol"] + BAGUA[low]["symbol"],
            "gong": gong,
            "gong_wuxing": GONG_WUXING[gong],
            "xiang": xiang,
            "brief": brief,
            "tendency": tendency,
            "advice": advice,
        }

    payload = {
        "meta": {
            "bagua_order": "先天八卦数：乾1 兑2 离3 震4 巽5 坎6 艮7 坤8",
            "note": "卦名与大象辞依《周易》通行本；八宫归属依京房八宫卦序",
        },
        "bagua": BAGUA,
        "gong_wuxing": GONG_WUXING,
        "gua": gua_map,
    }
    with open(os.path.join(ASSETS, "gua64.json"), "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=1)

    print(f"64卦数据生成完成：{len(gua_map)} 卦，八宫分布 {dict(c)}")
    for probe in ("乾为天", "地天泰", "水火既济", "水雷屯"):
        g = gua_map[probe]
        print(f"  {g['no']:>2} {g['name']} {g['symbol']} 宫{g['gong']}({g['gong_wuxing']}) {g['tendency']}")


if __name__ == "__main__":
    main()
