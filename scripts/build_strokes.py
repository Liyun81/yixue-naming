def build() -> Tuple[Dict[str, int], List[str]]:
    chars: Dict[str, int] = {}
    warnings: List[str] = []
    conflicts: List[str] = []

    for stroke, words in sorted(STROKE_DATA.items()):
        seen_in_group = set()
        for ch in words.split():
            if ch in seen_in_group:
                warnings.append(f"第{stroke}画组内重复：{ch}")
                continue
            seen_in_group.add(ch)
            if ch in chars and chars[ch] != stroke:
                # 简繁同形字（如 儿/兒、斗/鬥、台/臺）：本字优先，取较小笔画
                keep = min(chars[ch], stroke)
                warnings.append(
                    f"简繁同形：{ch} 同时出现于{chars[ch]}画与{stroke}画，按本字取{keep}画"
                )
                chars[ch] = keep
                continue
            chars[ch] = stroke

    # 取名高频字补遗（只补不覆盖）
    for ch, expect in EXTRA.items():
        if len(ch) != 1:
            conflicts.append(f"补遗表键必须为单字：{ch}")
            continue
        if ch not in chars:
            chars[ch] = expect
        elif chars[ch] != expect:
            warnings.append(f"补遗冲突：{ch} 现有{chars[ch]}画，补遗作{expect}画，保留现有")

    # 姓氏专项校准（以本表为准，差异记入软性提示便于复核）
    for ch, expect in SURNAMES.items():
        if ch in chars and chars[ch] != expect:
            warnings.append(f"姓氏校准：{ch} 语料作{chars[ch]}画，姓氏表作{expect}画，采用{expect}画")
        chars[ch] = expect

    for ch, expect in SENTINEL.items():
        got = chars.get(ch)
        if got is None:
            conflicts.append(f"易错字缺失：{ch}（应为{expect}画）")
        elif got != expect:
            conflicts.append(f"易错字笔画错误：{ch} 实际{got}，应为{expect}")

    return chars, warnings + conflicts


